def prim_types():
    name = input("Enter your name: ")
    name_upper = name.upper()
    print("Your name converted to upper case is:", name_upper)
    input_num = input("Enter an int number: ")
    number = int(input_num)
    result_int = number * 2
    print("The int number you entered multiplied by 2 is:", result_int)
    float_input = input("Enter a float number like (8.7):")
    number_float = float(float_input)
    result_float = number_float * 10
    print("The float number you entered multiplied by 10 is:", result_float)

